#Requires -Version 5.1
#Requires -PSEdition Desktop
<#
.SYNOPSIS
    Freezes REAL Windows PowerShell 5.1 fixtures produced by the released PraRemoteMailbox 2.2.0 code.
.DESCRIPTION
    PURPOSE. The PowerShell 7 migration of the engine must keep reading and restoring every backup, proof and
    Finalize package written by 2.x under Windows PowerShell 5.1, byte for byte. This tool produces those files
    once, with the 2.2.0 production code paths running under powershell.exe (5.1), so that
    tests\PraLegacyFixtures.Tests.ps1 can later prove the migrated engine still accepts them.

    NOTHING IS HAND-CRAFTED THAT PRODUCTION WOULD WRITE. The generator reuses the 2.2.0 test harness itself:
    it extracts the BeforeAll block of tests\PraRemoteMailbox.Tests.ps1 (synthetic ActiveDirectory module,
    synthetic Cloud barrier, New-GateRuntime, Invoke-GateProcess, the controlled signature substitution of
    tests\IntegrityFixture.ps1) from the SOURCE checkout and runs the real modules and the real entry script:
      - Convert backup and AD proof   : Invoke-PraAdBatch (PRA.Directory) -> Save-PraBatch -> PRA.Backup codec
      - Recover backup and proof      : Invoke-PraRemoteMailbox.ps1 -Action Recover -Phase AD, in a powershell.exe child
      - Finalize package              : Invoke-PraRemoteMailbox.ps1 -Action Recover -Phase Cloud (Save-PraFinalizePackage)
      - all-types raw capture         : ConvertTo-PraRawSnapshot + Write-PraRawCapture
    Only two things are emulated, because 2.2.0 can no longer write them: the legacy schema 1 and 2 files (JSON
    and historical CLIXML). They are built the way the 2.2.0 test-suite builds them (record from the production
    New-PraPlan, CLIXML from the genuine 5.1 PSSerializer of an object whose type names are the native ADUser
    ones), see Add-LegacySets.

    SYNTHETIC DATA ONLY. The harness domain names (gate.invalid) are rewritten to contoso.com before the harness
    runs. No directory, tenant, network or credential is touched. Object GUIDs, DNs, UPNs and attribute values
    are fixed by the harness. Batch IDs, run IDs and timestamps are generated by the production code at run
    time: regenerating therefore yields different file names and hashes (the fixtures are frozen once, and the
    committed copy is the reference).

    HOW TO REGENERATE (never part of the runtime package):
        git -C <repo> worktree add <scratch>\pra-2.2.0 v2.2.0            # the exact released source
        powershell.exe -NoProfile -File tools\New-LegacyFixtures.ps1 -SourceRoot <scratch>\pra-2.2.0 [-Force]
    Default output: tests\fixtures\ps51-2.2.0 of the repository that holds this script. The source checkout is
    only read. The generator refuses any engine other than 2.2.0 and any host other than Windows PowerShell 5.1.

    OUTPUT (output root):
        01-convert-users\        Convert schema 3, 2 users: JSON, .sha256, .clixml, Journal, State proof (+ .sha256)
        02-recover-users\        Recover schema 3 issued from 01, with its State proof
        03-finalize-shared13\    RecoverFinalize package (manifest schema 2 + copies of the lots) and cloud journal
        04-shared13            Journals and proofs of the 13-shared Convert and Recover lots (native security descriptors); their JSON/CLIXML are the copies held in 03
        05-legacy\schema1|2\     historical CLIXML (5.1 PSSerializer) + JSON schema 1 / 2
        06-all-types\            all-types.clixml written by the production codec (input: New-PraAllTypesUser.ps1)
        sets.json                machine-readable index used by the tests
        README.md, fixtures.sha256, .gitattributes
.PARAMETER SourceRoot
    Root of a 2.2.0 checkout (contains package\, tests\, CHANGELOG.md). Read only.
.PARAMETER OutputRoot
    Destination folder. Default: <repository>\tests\fixtures\ps51-2.2.0.
.PARAMETER WorkRoot
    Scratch folder for the harness (deleted at the end). Default: a new folder under the system temp path.
    Paths of the run appear in the journals: pass a neutral folder (for example C:\PraFx) to keep the user
    profile name out of the frozen files.
.PARAMETER Force
    Replace the generated content of an existing output root.
.EXAMPLE
    powershell.exe -NoProfile -File .\tools\New-LegacyFixtures.ps1 -SourceRoot C:\scratch\pra-2.2.0 -WorkRoot C:\PraFx
.NOTES
    Author  : Nicolas Fabert
    Version : 1.0.0 (tooling, independent of the engine version)
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory)][string]$SourceRoot,
    [string]$OutputRoot,
    [string]$WorkRoot,
    [switch]$Force
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
# A Windows PowerShell launched by pwsh can inherit only Core module paths.
foreach ($name in @('Microsoft.PowerShell.Utility', 'Microsoft.PowerShell.Management', 'Microsoft.PowerShell.Security')) {
    Import-Module (Join-Path $PSHOME ('Modules\' + $name + '\' + $name + '.psd1')) -ErrorAction Stop
}
if ($PSVersionTable.PSEdition -ne 'Desktop' -or $PSVersionTable.PSVersion.Major -ne 5) { throw 'Run this tool with powershell.exe (Windows PowerShell 5.1): the fixtures must be genuine 5.1 output.' }

$toolRoot = Split-Path -Parent $PSCommandPath
$repoRoot = [IO.Path]::GetFullPath((Join-Path $toolRoot '..'))
$SourceRoot = [IO.Path]::GetFullPath($SourceRoot)
if (-not $OutputRoot) { $OutputRoot = Join-Path $repoRoot 'tests\fixtures\ps51-2.2.0' }
$OutputRoot = [IO.Path]::GetFullPath($OutputRoot)
$allTypesInput = Join-Path $OutputRoot '06-all-types\New-PraAllTypesUser.ps1'
$utf8 = New-Object Text.UTF8Encoding($false)

# ---- source checks --------------------------------------------------------------------------------------------
foreach ($required in @('package\Invoke-PraRemoteMailbox.ps1', 'package\module\PRA.Backup.psm1', 'tests\PraRemoteMailbox.Tests.ps1', 'tests\IntegrityFixture.ps1', 'CHANGELOG.md')) {
    if (-not (Test-Path -LiteralPath (Join-Path $SourceRoot $required))) { throw "SourceRoot is not a PRA checkout: missing $required" }
}
$mainText = [IO.File]::ReadAllText((Join-Path $SourceRoot 'package\Invoke-PraRemoteMailbox.ps1'))
if ($mainText -notmatch "Show-PraGui -Root \`$PSScriptRoot -ConfigPath \`$ConfigPath -Version '2\.2\.0'") { throw 'SourceRoot is not engine 2.2.0 (expected the 2.2.0 entry script).' }
if (-not (Test-Path -LiteralPath $allTypesInput)) { throw "Missing input $allTypesInput (committed with the fixtures)." }
$sourceCommit = 'unknown'
$git = Get-Command git.exe -ErrorAction SilentlyContinue
if ($git) {
    try { $head = (& $git.Source -C $SourceRoot rev-parse HEAD 2>$null); if ($LASTEXITCODE -eq 0 -and $head) { $sourceCommit = ([string]$head).Trim() } } catch { $sourceCommit = 'unknown' }
}

# ---- output guard ---------------------------------------------------------------------------------------------
if (Test-Path -LiteralPath $OutputRoot) {
    $existing = @(Get-ChildItem -LiteralPath $OutputRoot -Force | Where-Object { $_.Name -ne '06-all-types' })
    $existing += @(Get-ChildItem -LiteralPath (Join-Path $OutputRoot '06-all-types') -Force -ErrorAction SilentlyContinue | Where-Object { $_.Name -ne 'New-PraAllTypesUser.ps1' })
    if ($existing.Count -and -not $Force) { throw "Output root already holds fixtures: $OutputRoot (use -Force to replace them)." }
    foreach ($item in $existing) { Remove-Item -LiteralPath $item.FullName -Recurse -Force }
}
$null = New-Item -ItemType Directory -Path (Join-Path $OutputRoot '06-all-types') -Force

# ---- harness extraction ---------------------------------------------------------------------------------------
$testFile = Join-Path $SourceRoot 'tests\PraRemoteMailbox.Tests.ps1'
$tokens = $null; $parseErrors = $null
$ast = [Management.Automation.Language.Parser]::ParseFile($testFile, [ref]$tokens, [ref]$parseErrors)
if ($parseErrors.Count) { throw 'The 2.2.0 test file does not parse.' }
$beforeAll = @($ast.FindAll({ param($node) $node -is [Management.Automation.Language.CommandAst] -and $node.GetCommandName() -eq 'BeforeAll' }, $true))[0]
$blockAst = @($beforeAll.CommandElements | Where-Object { $_ -is [Management.Automation.Language.ScriptBlockExpressionAst] })[0]
$harness = $blockAst.ScriptBlock.Extent.Text
$harness = $harness.Substring(1, $harness.Length - 2)
$harness = $harness.Replace('$PSScriptRoot', '$global:PraFxTestsDir')
# Synthetic naming: the harness uses reserved .invalid names; the frozen fixtures use the fictitious contoso names.
$harness = $harness.Replace('DC=gate,DC=invalid', 'DC=contoso,DC=com').Replace('gate.invalid', 'contoso.com').Replace('synthetic.mail.onmicrosoft.com', 'contoso.mail.onmicrosoft.com')

if (-not $WorkRoot) { $WorkRoot = Join-Path ([IO.Path]::GetTempPath()) ('PraFx-' + [guid]::NewGuid().ToString('N').Substring(0, 8)) }
$WorkRoot = [IO.Path]::GetFullPath($WorkRoot)
if ((Test-Path -LiteralPath $WorkRoot) -and @(Get-ChildItem -LiteralPath $WorkRoot -Force).Count) { throw "WorkRoot must be empty: $WorkRoot" }
$null = New-Item -ItemType Directory -Path $WorkRoot -Force
$global:PraFxTestsDir = Join-Path $SourceRoot 'tests'
$savedModulePath = $env:PSModulePath

function Get-FxFolders {
    param([string]$Root, [string]$Pattern = '*')
    @(Get-ChildItem -LiteralPath $Root -Directory -Filter $Pattern -ErrorAction SilentlyContinue | Sort-Object Name)
}

function Switch-FxRuntime {
    param($Runtime)
    $env:PRA_GATE_STATE = $Runtime.StatePath
    $env:PSModulePath = $Runtime.Modules + ';' + (Join-Path $PSHOME 'Modules')
    Import-Module ActiveDirectory -Force -Global
}

function Save-FxState {
    param($Runtime)
    # Persist only the ordinary mutable fake directory; native descriptors are injected into read copies.
    [IO.File]::WriteAllText($Runtime.StatePath, [Management.Automation.PSSerializer]::Serialize($global:PraGateAd, 35))
}

function Copy-FxFolder {
    param([string]$Folder, [string]$Set)
    $destination = Join-Path (Join-Path $OutputRoot $Set) (Split-Path $Folder -Leaf)
    $null = New-Item -ItemType Directory -Path (Split-Path $destination -Parent) -Force
    Copy-Item -LiteralPath $Folder -Destination $destination -Recurse
    return $destination
}

$sets = New-Object 'Collections.Generic.List[object]'
function Add-FxEntry {
    param([string]$Set, [string]$Role, [string]$Path, [hashtable]$Extra = @{})
    $relative = $Path.Substring($OutputRoot.Length).TrimStart('\').Replace('\', '/')
    $entry = [ordered]@{ Set = $Set; Role = $Role; Path = $relative }
    foreach ($key in $Extra.Keys) { $entry[$key] = $Extra[$key] }
    $sets.Add([pscustomobject]$entry)
}

function Get-FxBatchFiles {
    <# Locates the production files of one Batch-<id> folder. #>
    param([string]$Folder, [string]$Operation)
    $json = @(Get-ChildItem -LiteralPath $Folder -File -Filter ($Operation + '-*.json'))
    if ($json.Count -ne 1) { throw "Expected one $Operation JSON in $Folder" }
    $state = @(Get-ChildItem -LiteralPath $Folder -File -Filter 'State-*.json')
    [pscustomobject]@{
        Json = $json[0].FullName; Sha = $json[0].FullName + '.sha256'
        Raw = @(Get-ChildItem -LiteralPath $Folder -File -Filter '*.clixml')[0].FullName
        Journal = @(Get-ChildItem -LiteralPath $Folder -File -Filter 'Journal-*.jsonl')[0].FullName
        State = $(if ($state.Count) { $state[0].FullName } else { '' })
    }
}

function Add-FxBatch {
    param([string]$Set, [string]$Folder, [string]$Operation, [int]$Records, [string]$SourceKey = '')
    $files = Get-FxBatchFiles $Folder $Operation
    $extra = @{ Operation = $Operation; Records = $Records; Schema = 3 }
    Add-FxEntry $Set 'Backup' $files.Json $extra
    if ($files.State) { Add-FxEntry $Set 'Proof' $files.State @{ Operation = $Operation; Records = $Records; Backup = $files.Json.Substring($OutputRoot.Length).TrimStart('\').Replace('\', '/') } }
}

function Add-LegacySets {
    <# Schema 1 and 2 cannot be written by 2.2.0 any more: emulate them the way the 2.2.0 test-suite does. #>
    param($Runtime)
    Switch-FxRuntime $Runtime
    $context = New-GateContext $Runtime
    $plans = @(New-PraPlan $context 'user1' 'Convert'; New-PraPlan $context 'user2' 'Convert')
    if (-not ('Microsoft.ActiveDirectory.Management.ADUser' -as [type])) {
        # Native type names of Get-ADUser output (ADUser/ADAccount/ADPrincipal/ADObject) with CLR properties, so that the
        # genuine 5.1 serializer writes the same <TN> list and a <Props> block, ObjectGUID as <G>. Synthetic assembly.
        Add-Type -TypeDefinition @'
namespace Microsoft.ActiveDirectory.Management {
    public class ADObject {
        public System.Guid ObjectGUID { get; set; }
        public string DistinguishedName { get; set; }
        public string Name { get; set; }
        public string ObjectClass { get; set; }
        public long uSNChanged { get; set; }
        public override string ToString() { return DistinguishedName; }
    }
    public class ADPrincipal : ADObject { public string SamAccountName { get; set; } }
    public class ADAccount : ADPrincipal { public string UserPrincipalName { get; set; } public string DisplayName { get; set; } }
    public class ADUser : ADAccount {
        public string mail { get; set; }
        public string homeMDB { get; set; }
        public string homeMTA { get; set; }
        public string msExchHomeServerName { get; set; }
        public byte[] msExchMailboxGuid { get; set; }
        public bool mDBUseDefaults { get; set; }
        public int msExchRecipientDisplayType { get; set; }
        public long msExchRecipientTypeDetails { get; set; }
        public string extensionAttribute1 { get; set; }
        public string[] proxyAddresses { get; set; }
        public string[] memberOf { get; set; }
    }
}
'@
    } else { throw 'A Microsoft.ActiveDirectory.Management.ADUser type is already loaded: run the generator in a clean powershell.exe.' }
    $users = @(foreach ($index in 1, 2) {
            $source = New-GateUser $index
            $adUser = New-Object Microsoft.ActiveDirectory.Management.ADUser
            foreach ($property in @('ObjectGUID', 'DistinguishedName', 'Name', 'uSNChanged', 'SamAccountName', 'UserPrincipalName', 'DisplayName', 'mail', 'homeMDB', 'homeMTA',
                    'msExchHomeServerName', 'msExchMailboxGuid', 'mDBUseDefaults', 'msExchRecipientDisplayType', 'msExchRecipientTypeDetails', 'extensionAttribute1', 'proxyAddresses', 'memberOf')) {
                $adUser.$property = $source.$property
            }
            $adUser.ObjectClass = 'user'
            $adUser
        })
    foreach ($version in 1, 2) {
        $folder = Join-Path $OutputRoot ('05-legacy\schema' + $version)
        $null = New-Item -ItemType Directory -Path $folder -Force
        $raw = Join-Path $folder 'historical.clixml'
        [IO.File]::WriteAllText($raw, [Management.Automation.PSSerializer]::Serialize($users, 30))
        $records = @(foreach ($plan in $plans) {
                $record = $plan.Record | ConvertTo-Json -Depth 30 | ConvertFrom-Json
                if ($version -eq 1) { $record | Add-Member AddedToLicenseGroup $false }
                $record
            })
        $data = [ordered]@{ SchemaVersion = $version; Operation = 'Convert'; Environment = $context.Config.Environment; Records = @($records); RawFile = 'historical.clixml'; RawHash = (Get-PraHash $raw) }
        $path = Join-Path $folder 'historical.json'
        [IO.File]::WriteAllText($path, ($data | ConvertTo-Json -Depth 30))
        [IO.File]::WriteAllText(($path + '.sha256'), (Get-PraHash $path))
        Add-FxEntry ('05-legacy') 'LegacyBackup' $path @{ Operation = 'Convert'; Records = 2; Schema = $version; Legacy = ($version -eq 1) }
    }
}

try {
    $global:PraGate = $null
    . ([scriptblock]::Create($harness))
    $global:PraGate.Root = $WorkRoot   # harness runtime folders live under the neutral work root

    # ---- 05 legacy (fresh, unmodified directory) ---------------------------------------------------------------
    Add-LegacySets (New-GateRuntime -Name 'fx-legacy')

    # ---- 01 / 02 users: Convert in-process (production Invoke-PraAdBatch), Recover through the real entry script ------
    $runtime = New-GateRuntime -Name 'fx-users'
    Switch-FxRuntime $runtime
    $context = New-GateContext $runtime
    $plans = @(1..2 | ForEach-Object { New-PraPlan $context ('user' + $_) 'Convert' })
    $null = Invoke-PraAdBatch $context $plans 'Convert'
    Save-FxState $runtime
    $backups = $runtime.State.BackupFolder
    $convertFolder = (Get-FxFolders $backups 'Batch-*')[0].FullName
    $convertJson = (Get-FxBatchFiles $convertFolder 'Convert').Json
    $recover = Invoke-GateProcess $runtime @{ Action = 'Recover'; Mode = 'Apply'; Phase = 'AD'; Force = $true; ConfigPath = $runtime.ConfigPath; Batch = $convertJson } -TimeoutSeconds 120
    if ($recover.ExitCode -ne 0) { throw "Recover (users) returned exit code $($recover.ExitCode): $($recover.Error)" }
    $recoverFolder = @(Get-FxFolders $backups 'Batch-*' | Where-Object FullName -ne $convertFolder)[0].FullName
    Add-FxBatch '01-convert-users' (Copy-FxFolder $convertFolder '01-convert-users') 'Convert' 2
    Add-FxBatch '02-recover-users' (Copy-FxFolder $recoverFolder '02-recover-users') 'Recover' 2

    # ---- 03 / 04 thirteen shared mailboxes with native security descriptors, cloud-confirmed Finalize package ------------
    $runtime = New-GateRuntime -Name 'fx-shared13' -Shared13 -Case CloudConfirmed13
    Switch-FxRuntime $runtime
    $context = New-GateContext $runtime
    $plans = @(1..13 | ForEach-Object { New-PraPlan $context ('user' + $_) 'Convert' })
    $source = Invoke-PraAdBatch $context $plans 'Convert'
    Save-FxState $runtime
    $recover = Invoke-GateProcess $runtime @{ Action = 'Recover'; Mode = 'Apply'; Phase = 'AD'; Force = $true; ConfigPath = $runtime.ConfigPath; Batch = $source.Path } -TimeoutSeconds 120
    if ($recover.ExitCode -ne 2) { throw "Recover (shared13) returned exit code $($recover.ExitCode): $($recover.Error)" }
    $backups = $runtime.State.BackupFolder
    $convertFolder = Split-Path $source.Path -Parent
    $recoverFolder = @(Get-FxFolders $backups 'Batch-*' | Where-Object FullName -ne $convertFolder)[0].FullName
    $recoverJson = (Get-FxBatchFiles $recoverFolder 'Recover').Json
    $cloud = Invoke-GateProcess $runtime @{ Action = 'Recover'; Mode = 'Apply'; Phase = 'Cloud'; Force = $true; ConfigPath = $runtime.ConfigPath; Batch = $recoverJson } -TimeoutSeconds 120
    if ($cloud.ExitCode -ne 2) { throw "Recover cloud phase (shared13) returned exit code $($cloud.ExitCode): $($cloud.Error)" }
    $finalizeFolder = @(Get-FxFolders $backups 'Finalize-*')
    if ($finalizeFolder.Count -ne 1) { throw 'Expected exactly one Finalize package.' }
    # The Finalize package holds byte-identical copies of the Convert and Recover lots (JSON, .sha256, CLIXML): the
    # 13-shared lots are indexed from there (set 04) and only their journals and proofs are kept in 04 (size budget).
    $finalizeCopy = Copy-FxFolder $finalizeFolder[0].FullName '03-finalize-shared13'
    $manifest = @(Get-ChildItem -LiteralPath $finalizeCopy -File -Filter 'Finalize-*.json')
    if ($manifest.Count -ne 1) { throw 'Expected one Finalize manifest.' }
    foreach ($lot in @(@{ Folder = $convertFolder; Operation = 'Convert' }, @{ Folder = $recoverFolder; Operation = 'Recover' })) {
        $files = Get-FxBatchFiles $lot.Folder $lot.Operation
        $embedded = Join-Path $finalizeCopy (Split-Path $files.Json -Leaf)
        foreach ($pair in @(@($files.Json, $embedded), @($files.Sha, ($embedded + '.sha256')), @($files.Raw, (Join-Path $finalizeCopy (Split-Path $files.Raw -Leaf))))) {
            if ((Get-FileHash -LiteralPath $pair[0]).Hash -ne (Get-FileHash -LiteralPath $pair[1]).Hash) { throw "Finalize copy differs from its lot: $($pair[1])" }
        }
        $kept = Copy-FxFolder $lot.Folder '04-shared13'
        foreach ($drop in @($files.Json, $files.Sha, $files.Raw)) { Remove-Item -LiteralPath (Join-Path $kept (Split-Path $drop -Leaf)) -Force }
        $embeddedRelative = $embedded.Substring($OutputRoot.Length).TrimStart('\').Replace('\', '/')
        Add-FxEntry '04-shared13' 'Backup' $embedded @{ Operation = $lot.Operation; Records = 13; Schema = 3; Note = 'file lives in the Finalize package (set 03)' }
        if ($files.State) { Add-FxEntry '04-shared13' 'Proof' (Join-Path $kept (Split-Path $files.State -Leaf)) @{ Operation = $lot.Operation; Records = 13; Backup = $embeddedRelative } }
    }
    Add-FxEntry '03-finalize-shared13' 'FinalizeManifest' $manifest[0].FullName @{ Operation = 'RecoverFinalize'; Items = 13; Schema = 2 }
    foreach ($cloudFolder in @(Get-FxFolders $backups '*-cloud')) { $null = Copy-FxFolder $cloudFolder.FullName '03-finalize-shared13' }

    # ---- 06 all types: production codec, input from the committed builder ------------------------------------------------
    . $allTypesInput
    $user = New-PraAllTypesUser
    $snapshot = ConvertTo-PraRawSnapshot -User $user -CapturedUtc $script:PraAllTypesCapturedUtc
    $allTypesPath = Join-Path $OutputRoot '06-all-types\all-types.clixml'
    Write-PraRawCapture -Context @{ LogFile = ''; VerboseEnabled = $false } -LiteralPath $allTypesPath -Snapshots @($snapshot)
    Add-FxEntry '06-all-types' 'AllTypes' $allTypesPath @{ CapturedUtc = $script:PraAllTypesCapturedUtc; Records = 1 }
}
finally {
    $env:PSModulePath = $savedModulePath
    Remove-Item Env:\PRA_GATE_STATE -ErrorAction SilentlyContinue
    Remove-Item Env:\PRA_GATE_NONET -ErrorAction SilentlyContinue
    if (Test-Path -LiteralPath $WorkRoot) { Remove-Item -LiteralPath $WorkRoot -Recurse -Force -ErrorAction SilentlyContinue }
}

# ---- privacy gate: no profile path or local name may leak into a frozen file -----------------------------------------
$leakPatterns = @([regex]::Escape($env:USERNAME), [regex]::Escape($env:COMPUTERNAME), [regex]::Escape($env:USERPROFILE.Replace('\', '\\')), 'gate\.invalid')
foreach ($file in Get-ChildItem -LiteralPath $OutputRoot -Recurse -File | Where-Object Extension -ne '.ps1') {
    $text = [IO.File]::ReadAllText($file.FullName)
    foreach ($pattern in $leakPatterns) {
        if ($pattern -and $text -match $pattern) { throw "Privacy gate: '$pattern' found in $($file.FullName). Rerun with a neutral -WorkRoot." }
    }
}

# ---- index, provenance, hashes ---------------------------------------------------------------------------------------
[IO.File]::WriteAllText((Join-Path $OutputRoot 'sets.json'), (($sets | ConvertTo-Json -Depth 5) + "`n"), $utf8)
[IO.File]::WriteAllText((Join-Path $OutputRoot '.gitattributes'), "# Frozen byte-exact fixtures: no end-of-line or encoding normalisation.`n* -text`n", $utf8)

$sizes = @(Get-ChildItem -LiteralPath $OutputRoot -Recurse -File | Measure-Object Length -Sum)[0].Sum
$readme = @"
